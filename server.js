app.post('/api/generate-study-guide', async (req, res) => {
    try {
        const { topic, difficulty, studyTime, learningStyle, specificAreas } = req.body;

        if (!topic) {
            return res.status(400).json({ error: 'Topic is required' });
        }

        await new Promise(resolve => setTimeout(resolve, 2000));

        // Generate learning style-specific study guide
        const studyGuide = generateLearningStyleOptimizedGuide(topic, difficulty, studyTime, learningStyle, specificAreas);

        res.json({
            success: true,
            studyGuide: studyGuide,
            metadata: {
                topic,
                difficulty,
                studyTime,
                learningStyle,
                specificAreas,
                generatedAt: new Date().toISOString(),
                model: 'StudyGenie Smart Engine v2.0'
            }
        });

    } catch (error) {
        console.error('Error generating study guide:', error);
        res.status(500).json({ 
            error: 'Failed to generate study guide',
            details: error.message 
        });
    }
});

