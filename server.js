app.post('/api/download-pdf', async (req, res) => {
    try {
        const { studyGuide, metadata } = req.body;

        if (!studyGuide) {
            return res.status(400).json({ error: 'Study guide content is required' });
        }

        const htmlContent = md.render(studyGuide);
        
        const pdfHtml = createPdfTemplate(htmlContent, metadata);

        const options = {
            format: 'A4',
            printBackground: true,
            margin: {
                top: '0.5in',
                right: '0.5in',
                bottom: '0.5in',
                left: '0.5in'
            }
        };

        const file = { content: pdfHtml };
        const pdfBuffer = await htmlPdf.generatePdf(file, options);

        const fileName = `${metadata.topic.replace(/[^a-zA-Z0-9]/g, '_')}_StudyGuide.pdf`;
        
        res.setHeader('Content-Type', 'application/pdf');
        res.setHeader('Content-Disposition', `attachment; filename="${fileName}"`);
        res.setHeader('Content-Length', pdfBuffer.length);

        res.end(pdfBuffer);

    } catch (error) {
        console.error('Error generating PDF:', error);
        res.status(500).json({ 
            error: 'Failed to generate PDF',
            details: error.message 
        });
    }
});

